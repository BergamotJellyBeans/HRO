bool Frontend::process(float i, float q, std::complex<float>& output, bool rotate) {
    std::complex<float> sample{i, q};
    if (rotate) rotator_.process(&sample, 1);
    delay_[position_] = sample;
    position_ = (position_ + 1) % delay_.size();
    if (++decimation_ < 4) return false;
    decimation_ = 0;
    float oi = 0.0f, oq = 0.0f;
    unsigned index = (position_ + delay_.size() - 1) % delay_.size();
    for (unsigned k = 0; k < delay_.size(); ++k) {
        oi += taps[k] * delay_[index].real();
        oq += taps[k] * delay_[index].imag();
        index = index == 0 ? delay_.size() - 1 : index - 1;
    }
    output = {oi, oq};
    return true;
}
